import type { CountryPool } from './types'

/**
 * Curated Facts Quiz question bank — one deliberately authored entry per
 * canonical country, derived from (but never mechanically transformed
 * from) that country's canonical `fact` string in
 * data/countryDetails/countryRecords.ts. The prose "Did You Know?" fact
 * stays the single source of truth for Country Results/Study; this file is
 * a separate, purpose-built quiz representation of the same underlying
 * knowledge, matching the "explicit curated question bank" requirement for
 * Facts rather than deriving a question from the prose fact string at
 * runtime.
 *
 * `distractorIds` are curated per-question, not generated by the generic
 * `getDistractors()` tiering helper (see distractors.ts) — trivia
 * distractors need to be *semantically* plausible (a regional neighbour, a
 * country sharing the same historical/geographical trait, a country a
 * player could genuinely confuse with the answer), which a
 * continent/look-alike heuristic built for flag recognition can't produce.
 * Each entry always has exactly 3 distractor ids, verified distinct from
 * each other and from `countryId`, and checked not to also satisfy the
 * question's own wording (see factQuestions.test.ts's leak-check suite).
 *
 * `tier` reuses the existing CountryPool vocabulary ('familiar' / 'explorer'
 * / 'world-expert', already shown to players as "Easy" / "Medium" /
 * "Expert" — see COUNTRY_POOL_OPTIONS in config.ts) but means something
 * different here than it does for Flags/Capitals/Languages/Currencies: for
 * those modes CountryPool selects *which countries* a question may be
 * about (a geographic-familiarity curation), while for Facts it selects
 * which *trivia* is asked, based on how obscure the underlying knowledge
 * is — a global "everyone knows this" fact (Pyramids -> Egypt) is
 * 'familiar', a fact that needs real geography/history knowledge but isn't
 * obscure is 'explorer', and a fact that should make a knowledgeable player
 * think "I didn't know that" is 'world-expert'. The tiers nest exactly the
 * way FAMILIAR_COUNTRY_IDS/EXPLORER_COUNTRY_IDS already nest in pools.ts:
 * Easy's pool is 'familiar' entries only; Medium's is 'familiar' +
 * 'explorer'; Expert's is all 200. See eligibleFactEntries() in facts.ts.
 *
 * `typeAnswerEligible` is a deliberately conservative, per-question
 * assessment of whether the question's wording alone (with no Multiple
 * Choice options to lean on) still has exactly one defensible answer for a
 * knowledgeable player — not every fact clears that bar, and a handful are
 * Multiple-Choice-only for that reason (see the Facts Quiz implementation
 * report for the excluded-country list and reasoning).
 */
export interface FactEntry {
  /** data/countries.ts Country.id this entry is about. */
  countryId: string
  /** The full quiz prompt sentence — never the raw countryRecords.ts `fact` string verbatim. */
  question: string
  /** Exactly 3 curated, semantically-plausible wrong-answer country ids. */
  distractorIds: readonly [string, string, string]
  /** Trivia-knowledge difficulty — see the module doc comment above for why this isn't the geographic-familiarity meaning CountryPool has elsewhere. */
  tier: CountryPool
  /** Whether this question has one defensible answer without Multiple Choice options to disambiguate it. */
  typeAnswerEligible: boolean
}

